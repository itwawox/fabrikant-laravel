    private function __construct(private readonly string $key, private readonly ?Page $page) {}

    public static function for(string $key): self
    {
        return new self($key, Page::firstWhere('key', $key));
    }

    /** Текст блока: get('brewery.lede'); списки — массивом. Пустое в админке — текст по умолчанию. */
    public function get(string $path): mixed
    {
        $value = Arr::get($this->page->content ?? [], $path);

        return $value === null || $value === '' || $value === [] ? Arr::get(self::PAGES[$this->key]['content'], $path) : $value;
    }

    /** @return list<mixed> */
    public function list(string $path): array
    {
        return array_values((array) $this->get($path));
    }

    public function title(): string
    {
        return $this->page?->seo_title ?: self::PAGES[$this->key]['seo_title'];
    }

    public function description(string $season = ''): ?string
    {
        $text = $this->page?->seo_description ?: self::PAGES[$this->key]['seo_description'];

        return $text === null ? null : str_replace('{сезон}', $season, $text);
    }

    /** Картинка превью ссылки: загруженная в админке или по умолчанию; null — у страницы своя логика */
    public function image(): ?string
    {
        return $this->page?->og_image ? Storage::disk('public')->url($this->page->og_image) : self::PAGES[$this->key]['og_image'];
    }
