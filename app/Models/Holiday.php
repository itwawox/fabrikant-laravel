<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Attributes\Fillable;
use Illuminate\Database\Eloquent\Model;

// Праздник без года: month_day — «01-01», «05-09»
#[Fillable(['month_day', 'title'])]
class Holiday extends Model
{
    // Официальные нерабочие праздники РФ (ТК РФ, ст. 112). Переносы выходных каждый год свои — их заводят
    // в «Дни без акций»
    public const OFFICIAL = [
        '01-01' => 'Новогодние каникулы', '01-02' => 'Новогодние каникулы', '01-03' => 'Новогодние каникулы',
        '01-04' => 'Новогодние каникулы', '01-05' => 'Новогодние каникулы', '01-06' => 'Новогодние каникулы',
        '01-07' => 'Рождество Христово', '01-08' => 'Новогодние каникулы',
        '02-23' => 'День защитника Отечества', '03-08' => 'Международный женский день',
        '05-01' => 'Праздник Весны и Труда', '05-09' => 'День Победы', '06-12' => 'День России',
        '11-04' => 'День народного единства',
    ];

    private const MONTHS = ['января', 'февраля', 'марта', 'апреля', 'мая', 'июня', 'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря'];

    // «9 мая» вместо «05-09»
    public function label(): string
    {
        [$month, $day] = array_map('intval', explode('-', $this->month_day));

        return $day.' '.(self::MONTHS[$month - 1] ?? '');
    }
}
